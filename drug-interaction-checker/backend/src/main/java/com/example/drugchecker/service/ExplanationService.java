package com.example.drugchecker.service;

import com.example.drugchecker.model.Severity;
import org.springframework.stereotype.Service;

/**
 * Builds a doctor/user-readable explanation strictly grounded in
 * database-verified interaction data. Never invents dosages,
 * alternative medicines, or diagnoses.
 */
@Service
public class ExplanationService {

    public static final String CONSULT_WARNING =
            "Do not start, stop, or change prescribed medication without consulting a qualified healthcare professional.";

    public String buildExplanation(String drug1, String drug2, Severity severity, String interactionDescription) {
        StringBuilder sb = new StringBuilder();
        switch (severity) {
            case HIGH -> sb.append("This combination is flagged as a HIGH severity interaction in the reference database. ");
            case MODERATE -> sb.append("This combination is flagged as a MODERATE severity interaction in the reference database. ");
            case LOW -> sb.append("This combination is flagged as a LOW severity interaction in the reference database. ");
            default -> sb.append("No clinically significant interaction is recorded in the reference database for this combination. ");
        }
        if (interactionDescription != null && !interactionDescription.isBlank()) {
            sb.append("Recorded detail: ").append(interactionDescription).append(" ");
        }
        sb.append("Clinical judgement should always take priority over this automated summary.");
        return sb.toString();
    }

    public String buildNoRecordExplanation(String drug1, String drug2) {
        return "No known interaction between " + drug1 + " and " + drug2 +
               " was found in the current local database. This does NOT mean no interaction " +
               "exists in the real world - it only reflects the current contents of this demo database.";
    }

    public String buildMlDisclaimerSuffix() {
        return " This severity was generated by a machine-learning model, not verified clinical data, " +
               "and should be treated as a preliminary estimate only, not medical certainty.";
    }
}
